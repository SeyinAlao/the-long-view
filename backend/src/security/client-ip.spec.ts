import { clientIpKey } from './client-ip';

describe('clientIpKey', () => {
  it.each([
    ['203.0.113.7', '203.0.113.7'],
    [' 203.0.113.7 ', '203.0.113.7'],
    ['::ffff:203.0.113.7', '203.0.113.7'],
    ['2001:db8:1:2:3:4:5:6', '2001:0db8:0001:0002::/64'],
    ['2001:db8:1:2::9', '2001:0db8:0001:0002::/64'],
    ['2001:0DB8:0001:0002:ffff::1', '2001:0db8:0001:0002::/64'],
    ['2001:db8::1', '2001:0db8:0000:0000::/64'],
    ['::1', '0000:0000:0000:0000::/64'],
  ])('%s is counted as %s', (value, key) => {
    expect(clientIpKey(value)).toBe(key);
  });

  it.each([[undefined], [''], ['not-an-ip'], ['203.0.113.7, 198.51.100.1'], ['999.1.1.1'], ['2001:db8::1::2']])(
    'refuses %p',
    (value) => {
      expect(clientIpKey(value)).toBeNull();
    },
  );
});
